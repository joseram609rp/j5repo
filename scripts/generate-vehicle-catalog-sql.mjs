import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source = readFileSync(new URL('../data/vehicle-catalog/vehicle_catalog_final.json', import.meta.url), 'utf8');
const { brands } = JSON.parse(source);
const key = s => s.trim().normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
if (brands.length !== 57 || brands.reduce((n,b)=>n+b.models.length,0) !== 986 || new Set(brands.map(b=>key(b.make))).size !== 57) throw Error('CATALOG_COUNTS');
for (const b of brands) if (new Set(b.models.map(key)).size !== b.models.length) throw Error('CATALOG_DUPLICATES');
const quote = s => "N'" + s.replaceAll("'", "''") + "'";
let sql = '-- Generated by scripts/generate-vehicle-catalog-sql.mjs; JSON SHA256: ' + createHash('sha256').update(source.replace(/\r\n/g,'\n')).digest('hex') + '\nSET XACT_ABORT ON;\n';
sql += `CREATE TABLE dbo.VehicleMakes (
 id int IDENTITY NOT NULL CONSTRAINT PK_VehicleMakes PRIMARY KEY,
 name nvarchar(100) NOT NULL,
 normalized_name AS (LTRIM(RTRIM(name)) COLLATE Latin1_General_100_CI_AI) PERSISTED,
 active bit NOT NULL CONSTRAINT DF_VehicleMakes_Active DEFAULT 1,
 created_at datetime2(3) NOT NULL CONSTRAINT DF_VehicleMakes_Created DEFAULT SYSUTCDATETIME()
);
CREATE UNIQUE INDEX UX_VehicleMakes_Normalized ON dbo.VehicleMakes(normalized_name);
CREATE TABLE dbo.VehicleModels (
 id int IDENTITY NOT NULL CONSTRAINT PK_VehicleModels PRIMARY KEY,
 make_id int NOT NULL CONSTRAINT FK_VehicleModels_Make REFERENCES dbo.VehicleMakes(id),
 name nvarchar(150) NOT NULL,
 normalized_name AS (LTRIM(RTRIM(name)) COLLATE Latin1_General_100_CI_AI) PERSISTED,
 active bit NOT NULL CONSTRAINT DF_VehicleModels_Active DEFAULT 1,
 created_at datetime2(3) NOT NULL CONSTRAINT DF_VehicleModels_Created DEFAULT SYSUTCDATETIME()
);
CREATE UNIQUE INDEX UX_VehicleModels_Make_Normalized ON dbo.VehicleModels(make_id,normalized_name);
`;
sql += 'INSERT dbo.VehicleMakes(name) VALUES\n' + brands.map(b=>'('+quote(b.make)+')').join(',\n')+';\n';
for (const b of brands) sql += 'INSERT dbo.VehicleModels(make_id,name) SELECT m.id,v.name FROM dbo.VehicleMakes m CROSS JOIN (VALUES\n'+b.models.map(m=>'('+quote(m)+')').join(',\n')+') v(name) WHERE m.normalized_name='+quote(b.make)+' COLLATE Latin1_General_100_CI_AI;\n';
sql += `IF (SELECT COUNT(*) FROM dbo.VehicleMakes)<>57 OR (SELECT COUNT(*) FROM dbo.VehicleModels)<>986
 OR EXISTS(SELECT normalized_name FROM dbo.VehicleMakes GROUP BY normalized_name HAVING COUNT(*)>1)
 OR EXISTS(SELECT make_id,normalized_name FROM dbo.VehicleModels GROUP BY make_id,normalized_name HAVING COUNT(*)>1)
 OR EXISTS(SELECT 1 FROM dbo.VehicleModels v LEFT JOIN dbo.VehicleMakes m ON m.id=v.make_id WHERE m.id IS NULL)
 THROW 51010,'CATALOG_SEED_INVALID',1;
`;
const target = new URL('../database/migrations/010_vehicle_catalog.sql', import.meta.url);
if (process.argv.includes('--check')) { if (readFileSync(target,'utf8').replace(/\r\n/g,'\n') !== sql) throw Error('CATALOG_SEED_OUTDATED'); }
else writeFileSync(target, sql);
